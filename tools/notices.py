"""Write THIRD_PARTY_NOTICES.md and the README Credits section from the source of truth:

* the credit roll comes from the app itself (starextractor/ui/about.py CREDITS), never retyped;
* the Python packages and their licences come from the installed metadata of the runtime dependencies
  (the closure of starextractor's requirements), not from memory.

    python tools/notices.py          # rewrite both files
    python tools/notices.py --check  # exit 1 if either is out of date (CI)
"""
from __future__ import annotations

import argparse
import os
import re
import sys
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
START, END = "<!-- credits:start -->", "<!-- credits:end -->"


def credits_markdown() -> str:
    os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
    from starextractor.ui.about import CREDITS

    out: list[str] = []
    for style, text in CREDITS:
        if style == "title":
            out.append(f"**{text}**  ")
        elif style == "sub":
            out.append(f"{text}")
        elif style == "head":
            out.append(f"\n### {text.title()}")
        elif style == "label":
            out.append(f"\n**{text}**  ")
        elif style == "text":
            out.append(f"{text}  ")
        else:
            out.append("")
    text = "\n".join(line.rstrip() if not line.endswith("  ") else line for line in out).strip()
    return re.sub(r"\n{3,}", "\n\n", text) + "\n"


def _req_name(req: str) -> str | None:
    if ";" in req and "extra ==" in req:  # optional extras are not bundled
        return None
    m = re.match(r"\s*([A-Za-z0-9_.\-]+)", req)
    return m.group(1) if m else None


def runtime_closure(root: str = "starextractor") -> list[metadata.Distribution]:
    seen: dict[str, metadata.Distribution] = {}
    todo = [root]
    while todo:
        name = todo.pop()
        key = re.sub(r"[-_.]+", "-", name).lower()
        if key in seen:
            continue
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            continue
        seen[key] = dist
        todo += [n for r in (dist.requires or []) if (n := _req_name(r))]
    seen.pop("starextractor", None)
    return sorted(seen.values(), key=lambda d: d.metadata["Name"].lower())


def licence_of(d: metadata.Distribution) -> str:
    m = d.metadata
    expr = m.get("License-Expression")
    if expr:
        return expr
    lic = (m.get("License") or "").strip()
    if lic and len(lic) < 80 and "\n" not in lic:
        return lic
    classes = [c.split("::")[-1].strip() for c in m.get_all("Classifier") or [] if c.startswith("License ::")]
    return ", ".join(classes) or (lic.splitlines()[0][:80] if lic else "see the package")


def homepage(d: metadata.Distribution) -> str:
    m = d.metadata
    if m.get("Home-page"):
        return m["Home-page"]
    for url in m.get_all("Project-URL") or []:
        label, _, link = url.partition(",")
        if label.strip().lower() in ("homepage", "home", "source", "repository", "source code"):
            return link.strip()
    return ""


def notices() -> str:
    rows = [f"| {d.metadata['Name']} | {d.version} | {licence_of(d)} | {homepage(d)} |" for d in runtime_closure()]
    return f"""# Third-party notices

Star ExTractor is released under the MIT licence (see `LICENSE`). It bundles the data and software below.
This file is generated by `tools/notices.py` from the app's credit roll and the installed package metadata.

## Credits (the same text as the About window)

{credits_markdown()}
## Python packages

Runtime dependencies of `starextractor` and everything they require, as installed when this file was generated
(`pip install -e .`). Each package keeps its own licence. The Windows build leaves out the parts the app does not
use (for example Qt WebEngine, Qt PDF and Qt Quick from the PySide6 packages; see `packaging/starex_extractor.spec`).

| Package | Version | Licence | Home page |
|---|---|---|---|
{chr(10).join(rows)}

## Qt and PySide6 (LGPL v3)

The user interface uses Qt through PySide6 (Qt for Python), licensed under the GNU Lesser General Public
Licence v3 (LGPL-3.0). The Windows build is a PyInstaller **one-folder** build: the Qt and PySide6 libraries are
separate, dynamically linked DLL and .pyd files in the `_internal` folder, not compiled into the program. You may
replace them with your own compatible build of Qt/PySide6 (same major version) by swapping those files, and you
can rebuild the whole application from this repository (`packaging/build.ps1`). The Qt source code is available
from https://download.qt.io/ and the PySide6 source from https://code.qt.io/cgit/pyside/pyside-setup.git/.
The LGPL-3.0 and GPL-3.0 texts are included with PySide6 in the build.

## Bundled data

* Pickles (1998) stellar flux library (`starextractor/reference_spectra/`), see the credits above and
  `README.HILIB` in that folder.
* Reference-star catalogue (`starextractor/data/reference_stars.csv`), see the credits above.
* AAVSO telluric line list (`starextractor/data/aavso_telluric_lines.csv`), from the AAVSO Spectroscopy
  Database Users Manual v1.4, appendix A.1.
* Kitt Peak atmospheric extinction (`starextractor/data/kpnoextinct.dat`), from IRAF `noao/lib/onedstds`.
* ZWO ASI585MM Pro gain/read-noise table (`starextractor/data/asi585mm_pro.csv`), from ZWO's published
  specifications.
"""


def update_readme(text: str) -> str:
    block = f"{START}\n{credits_markdown()}{END}"
    if START in text and END in text:
        return re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _m: block, text, flags=re.DOTALL)
    return text.rstrip() + "\n\n## Credits\n\n" + block + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    from PySide6.QtWidgets import QApplication

    QApplication.instance() or QApplication([])
    targets = {ROOT / "THIRD_PARTY_NOTICES.md": notices()}
    readme = ROOT / "README.md"
    targets[readme] = update_readme(readme.read_text(encoding="utf-8"))
    def norm(text: str) -> str:  # a newer patch release of a package is not "out of date": ignore the versions
        return re.sub(r"^(\| [^|]+ \| )[^|]+( \|)", r"\1-\2", text, flags=re.MULTILINE)

    stale = [p.name for p, t in targets.items()
             if not p.exists() or norm(p.read_text(encoding="utf-8")) != norm(t)]
    if a.check:
        print("out of date: " + ", ".join(stale) if stale else "notices up to date")
        return 1 if stale else 0
    for p, t in targets.items():
        p.write_text(t, encoding="utf-8")
        print("wrote", p.name)
    return 0


if __name__ == "__main__":
    sys.exit(main())
